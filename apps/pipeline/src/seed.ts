import type { AggregatedItem } from '../../api/src/contract.ts';
import { computeClusterId, computeContentHash } from './harvester.ts';

function buildSeedItem(input: {
  id: string;
  source_id: string;
  source_priority: 1 | 2 | 3 | 4;
  item_index: number;
  title: string;
  source_name: string;
  original_language: string;
  continent: AggregatedItem['continent'];
  country: string | null;
  pillar: AggregatedItem['pillar'];
  category: AggregatedItem['category'];
  hoursAgo?: number;
  publishedAtIso: string;
  deadlineAtIso?: string | null;
  deadlineDaysFromNow?: number | null;
  canonical_url: string;
  verification_status?: AggregatedItem['verification_status'];
}): AggregatedItem {
  const now = Date.now();
  const published = input.publishedAtIso;
  const pubMs = Date.parse(published) || now;
  const fetched = new Date(Math.min(now, Math.max(pubMs + 1_800_000, now - 3_600_000))).toISOString();

  let deadline_at: string | null = null;
  if (input.deadlineAtIso !== undefined) {
    deadline_at = input.deadlineAtIso;
  } else if (input.deadlineDaysFromNow !== undefined && input.deadlineDaysFromNow !== null) {
    deadline_at = new Date(now + input.deadlineDaysFromNow * 86_400_000).toISOString();
  }

  return {
    id: input.id,
    source_id: input.source_id,
    source_priority: input.source_priority,
    item_index: input.item_index,
    cluster_id: computeClusterId(input.title),
    content_hash: computeContentHash(input.title, input.canonical_url),
    title: input.title,
    source_name: input.source_name,
    source_logo: null,
    original_language: input.original_language,
    continent: input.continent,
    country: input.country,
    pillar: input.pillar,
    category: input.category,
    published_at: published,
    fetched_at: fetched,
    deadline_at,
    expires_at: deadline_at,
    verified_at: input.verification_status === 'rejected' ? null : fetched,
    recheck_at:
      input.verification_status === 'rejected'
        ? null
        : new Date(now + 24 * 3_600_000).toISOString(),
    canonical_url: input.canonical_url,
    verification_status: input.verification_status ?? 'verified',
  };
}

